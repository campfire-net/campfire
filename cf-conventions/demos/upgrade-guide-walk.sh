# Check that rationale sections exist for key breaking changes
check_text() {
  local label="$1"
  local pattern="$2"
  if grep -qE "$pattern" "$GUIDE_PATH"; then
    ok "$label"
  else
    fail "$label — pattern '$pattern' not found in guide"
  fi
}

