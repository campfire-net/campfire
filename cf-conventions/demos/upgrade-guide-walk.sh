#!/usr/bin/env bash
# upgrade-guide-walk.sh
#
# Demo for campfireagent-901.
# Verifies that docs/upgrade-0.19-to-0.30.md exists and that every Go code
# snippet it contains compiles correctly against the current campfire module.
#
# Strategy:
#   1. Confirm the guide document exists.
#   2. Extract all ```go blocks from the guide, wrap each in a minimal main package,
#      and attempt `go build` from within a temp module that replaces the campfire
#      module with the local worktree.
#   3. Report pass/fail per snippet. Exit 1 if any snippet fails.
#
# Six-condition done §10:
#   This script IS the failing test for a spec-only item — it fails before the
#   guide is written and passes after.
#
# Exit codes:
#   0 — all checks pass
#   1 — one or more checks failed
#
# Usage:
#   bash cf-conventions/demos/upgrade-guide-walk.sh
#
# Run from the campfire repo root.

set -uo pipefail

# Locate the Go toolchain — prefer the standard install location.
GO_BIN="$(which go 2>/dev/null || echo "")"
if [[ -z "$GO_BIN" ]]; then
  for candidate in /usr/local/go/bin/go ~/go/bin/go /usr/go/bin/go; do
    if [[ -x "$candidate" ]]; then
      GO_BIN="$candidate"
      break
    fi
  done
fi
if [[ -z "$GO_BIN" ]]; then
  echo "ERROR: go toolchain not found; ensure 'go' is on PATH or install at /usr/local/go"
  exit 1
fi

GUIDE="docs/upgrade-0.19-to-0.30.md"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TMPDIR_BASE="$(mktemp -d)"
PASS=0
FAIL=0
SKIP=0

trap 'rm -rf "$TMPDIR_BASE"' EXIT

ok()   { echo "  [PASS] $1"; PASS=$((PASS + 1)); }
fail() { echo "  [FAIL] $1"; FAIL=$((FAIL + 1)); }
skip() { echo "  [SKIP] $1"; SKIP=$((SKIP + 1)); }

# ---------------------------------------------------------------------------
# §A — Document existence
# ---------------------------------------------------------------------------
echo ""
echo "=== §A — Guide document existence ==="

if [[ -f "$REPO_ROOT/$GUIDE" ]]; then
  ok "upgrade guide exists at $GUIDE"
else
  fail "upgrade guide missing: $GUIDE"
  echo ""
  echo "RESULT: FAIL (guide not found — create it first)"
  exit 1
fi

# ---------------------------------------------------------------------------
# §B — Required sections present
# ---------------------------------------------------------------------------
echo ""
echo "=== §B — Required sections ==="

GUIDE_PATH="$REPO_ROOT/$GUIDE"

required_sections=(
  "BC-1"
  "BC-2"
  "BC-3"
  "BC-4"
  "BC-5"
  "BC-6"
  "BC-7"
  "BC-8"
  "BC-9"
  "BC-10"
  "BC-11"
  "BC-12"
  "BC-13"
  "BC-14"
  "BC-15"
  "BC-16"
  "BC-17"
  "BC-18"
  "Consumer: \`rd\`"
  "Consumer: \`dontguess\`"
  "Consumer: \`social\`"
  "Consumer: \`the reach\`"
  "Consumer: \`freeso\`"
  "Decision Tree"
  "Wire-Format Compatibility"
  "Compatibility Floor Summary"
)

for section in "${required_sections[@]}"; do
  if grep -qF "$section" "$GUIDE_PATH"; then
    ok "section '$section' present"
  else
    fail "section '$section' missing"
  fi
done

# ---------------------------------------------------------------------------
# §C — Compile-check: build all snippets as a single package inside the
#      campfire module tree (no replace directive needed).
# ---------------------------------------------------------------------------
echo ""
echo "=== §C — Go snippet compilation checks ==="

# Strategy:
#   Write all snippets into a temporary package directory INSIDE the campfire
#   module. Each snippet becomes a function. After collecting all snippets,
#   build the package once. This avoids go.mod/replace-directive issues since
#   the snippets ARE part of the campfire module.
#
SNIPPET_PKG_DIR="$REPO_ROOT/internal/upgrade_guide_snippets"
mkdir -p "$SNIPPET_PKG_DIR"
trap 'rm -rf "$SNIPPET_PKG_DIR"; rm -rf "$TMPDIR_BASE"' EXIT

SNIPPET_NUM=0
SNIPPET_FILE="$SNIPPET_PKG_DIR/snippets.go"

# Write the file header.
cat > "$SNIPPET_FILE" << 'GOHEADER'
// Code generated by upgrade-guide-walk.sh — DO NOT EDIT.
// This file is generated during the demo run and deleted afterwards.
//
//go:build upgrade_guide_snippets

package snippets

