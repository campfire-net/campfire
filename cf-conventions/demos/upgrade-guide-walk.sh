	cfsession   "github.com/campfire-net/campfire/cf-conventions/cf-session"
	cfdiscovery "github.com/campfire-net/campfire/cf-conventions/cf-discovery"
	"github.com/campfire-net/campfire/cf-conventions/cf-authority/trust"
)

// Suppress unused imports.
var (
	_ = context.Background
	_ = ed25519.PublicKey{}
	_ = fmt.Println
	_ = strings.HasPrefix
	_ = time.Hour
	_ = cfprotocol.CampfireTagPrefix
	_ = convention.NewExecutor
	_ = cfsession.KeyHandlingJail
	_ = cfdiscovery.ErrInviteOnly
	_ = trust.DenyExpired
