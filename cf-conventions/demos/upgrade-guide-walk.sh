# ---------------------------------------------------------------------------
# §C-BUILD — Compile all collected snippets at once
# ---------------------------------------------------------------------------
echo ""
echo "  Building all snippets ($(wc -l < "$SNIPPET_FILE") lines) ..."

BUILD_OUT=$(cd "$REPO_ROOT" && "$GO_BIN" build -tags upgrade_guide_snippets ./internal/upgrade_guide_snippets/ 2>&1)
BUILD_EXIT=$?

if [[ $BUILD_EXIT -eq 0 ]]; then
  # All snippets compiled — mark each label as passing.
  for label in "${SNIPPET_LABELS[@]}"; do
    ok "$label"
  done
else
  # Build failed — report the error against each snippet (rough heuristic:
  # snippet_N in the error points to the failing function name).
  echo "  Build error:"
  echo "$BUILD_OUT" | sed 's/^/    /'
  for label in "${SNIPPET_LABELS[@]}"; do
    fail "$label (see build error above)"
  done
fi

# ---------------------------------------------------------------------------
# §D — Key structural invariants in the guide text
