GOHEADER

SNIPPET_LABELS=()

# compile_snippet: append snippet code as a function to SNIPPET_FILE.
# The actual build happens in §C-BUILD after all snippets are collected.
compile_snippet() {
  local label="$1"
  local code="$2"
  SNIPPET_NUM=$((SNIPPET_NUM + 1))
  SNIPPET_LABELS+=("$label")

  # Append a function for this snippet.
  cat >> "$SNIPPET_FILE" << GOFUNC
func snippet_${SNIPPET_NUM}() {
${code}
}

GOFUNC
}

